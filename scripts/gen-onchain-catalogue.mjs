#!/usr/bin/env node
// Generates src/data/onchainCatalogue.ts from the onchain-packs catalogue (DWLF-621).
//   node scripts/gen-onchain-catalogue.mjs /Users/Shared/btcnode-src/onchain-packs
// Source of truth: <packs>/catalogue.json (generated there by catalogue.py) and <packs>/docs/packs/*.md (the pack
// overviews, the same text as docs/llms.txt). Re-run whenever the packs catalogue changes; the output is committed.
// Direction labels are deliberately NOT copied: the tool describes conditions, not calls.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const packsDir = process.argv[2];
if (!packsDir) {
  console.error('usage: node scripts/gen-onchain-catalogue.mjs <onchain-packs dir>');
  process.exit(2);
}
const cat = JSON.parse(readFileSync(join(packsDir, 'catalogue.json'), 'utf8'));

const firstParagraph = (md) => md.split('\n\n').map((p) => p.trim()).find((p) => p && !p.startsWith('#')) || '';
const packIds = [...new Set(cat.types.map((t) => t.pack))];
const packs = Object.fromEntries(packIds.map((id) => {
  const md = readFileSync(join(packsDir, 'docs', 'packs', `${id}.md`), 'utf8');
  const title = (md.match(/^#\s+(.+?)\s*\(`/m) || md.match(/^#\s+(.+)$/m) || [null, id])[1];
  return [id, { title, summary: firstParagraph(md), count: cat.types.filter((t) => t.pack === id).length }];
}));

// The v1 cost-basis types (onchain-export design §4), written by the onchain-export validator (DWLF-593), not by the
// packs. Kept here so one tool describes every onchain.* type.
const COST_BASIS = [
  ['onchain.realised_price.cross.above', 'The daily close crossed above the realised price (the average price at which every coin last moved).'],
  ['onchain.realised_price.cross.below', 'The daily close crossed below the realised price.'],
  ['onchain.sth_realised_price.cross.above', 'The daily close crossed above the short-term-holder realised price (coins that moved in the last ~155 days): recent buyers back in profit on average.'],
  ['onchain.sth_realised_price.cross.below', 'The daily close crossed below the short-term-holder realised price: recent buyers in loss on average.'],
  ['onchain.lth_realised_price.cross.above', 'The daily close crossed above the long-term-holder realised price.'],
  ['onchain.lth_realised_price.cross.below', 'The daily close crossed below the long-term-holder realised price.'],
  ['onchain.mvrv.deep_value.enter', 'MVRV (market value / realised value) fell below 1.0.'],
  ['onchain.mvrv.deep_value.exit', 'MVRV back at 1.0 or above.'],
  ['onchain.mvrv.overheated.enter', 'MVRV rose above 3.5.'],
  ['onchain.mvrv.overheated.exit', 'MVRV back at 3.5 or below.'],
  ['onchain.supply_in_profit.capitulation.enter', 'Share of supply in profit fell below 50 %.'],
  ['onchain.supply_in_profit.capitulation.exit', 'Share of supply in profit back at 50 % or above.'],
  ['onchain.sth_sopr.reclaim', '7-day short-term-holder SOPR crossed back above 1 (coins moved by recent holders realised a profit on average).'],
  ['onchain.sth_sopr.lose', '7-day short-term-holder SOPR fell below 1 (coins moved by recent holders realised a loss on average).'],
].map(([id, meaning]) => ({
  id, pack: 'costBasis', meaning, inputs: 'BRK realised-price, MVRV, supply-in-profit and SOPR series (onchain-export design §2)',
  historyStart: '2015-01-22', threshold: null, caveats: 'Thresholds are the common public bands, fitted to ~3 cycles.',
  granularity: 'daily', keySuffix: null, estimated: false, methodVersion: 1, frequency: null,
}));
packs.costBasis = {
  title: 'Cost basis (v1)',
  summary: 'Price against the realised, short-term-holder and long-term-holder realised price, plus MVRV, supply-in-profit and STH-SOPR bands. Read as a ladder by dwlf_get_conditions.',
  count: COST_BASIS.length,
};

const entries = [
  ...COST_BASIS,
  ...cat.types.map((t) => ({
    id: t.id, pack: t.pack, meaning: t.meaning, inputs: t.inputs ?? null, historyStart: t.historyStart ?? null,
    threshold: t.threshold ?? null, caveats: t.caveats ?? null, granularity: t.granularity ?? null,
    keySuffix: t.keySuffix ?? null, estimated: Boolean(t.estimated), methodVersion: t.methodVersion ?? null,
    frequency: t.frequency ? { perYear: t.frequency.perYear ?? null, last3y: t.frequency.last3y ?? null, first: t.frequency.first ?? null, last: t.frequency.last ?? null } : null,
  })),
];

const header = `// GENERATED by scripts/gen-onchain-catalogue.mjs from the onchain-packs catalogue (asOf ${cat.asOf}, BRK ${cat.brkVersion}).
// Do not edit by hand: re-run the script. ${entries.length} event types in ${Object.keys(packs).length} packs.
`;
const body = `${header}
export interface OnchainEventEntry {
  id: string;
  pack: string;
  meaning: string;
  inputs: string | null;
  historyStart: string | null;
  threshold: string | null;
  caveats: string | null;
  granularity: string | null;
  keySuffix: string | null;
  estimated: boolean;
  methodVersion: number | null;
  frequency: { perYear: number | null; last3y: number | null; first: string | null; last: string | null } | null;
}

export const ONCHAIN_CATALOGUE_AS_OF = ${JSON.stringify(cat.asOf)};
export const ONCHAIN_CATALOGUE_BRK_VERSION = ${JSON.stringify(cat.brkVersion)};

export const ONCHAIN_PACKS: Record<string, { title: string; summary: string; count: number }> = ${JSON.stringify(packs, null, 2)};

export const ONCHAIN_EVENTS: OnchainEventEntry[] = ${JSON.stringify(entries, null, 2)};
`;
const out = new URL('../src/data/onchainCatalogue.ts', import.meta.url);
writeFileSync(out, body);
console.log(`wrote ${out.pathname}: ${entries.length} types, packs ${Object.keys(packs).join(', ')}`);
