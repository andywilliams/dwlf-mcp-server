#!/usr/bin/env node
/**
 * Vendors the one wording list Block shows (DWLF-804, WP7 charter check 7) and the one JS port of its rules:
 *   - the list: block-site `ops/wording-banned.json` (the export of its `wording.py`), byte for byte;
 *   - the port: dwlf-block-api `src/legibility/bannedWords.ts` (`bannedWordIn`, held to the site's verdicts by that
 *     repo's parity corpus), turned into plain ESM here. There is no third port: the transform only drops the type
 *     annotations and swaps the JSON import, and it refuses a source it does not recognise.
 * Both come from one named commit of each repo's main, recorded with their sha256 in eval/wording/SOURCES.json.
 *
 *   npm run wording:sync                   copy both from each repo's main (needs `gh` signed in); commit the result alone
 *   npm run wording:sync -- --check        exit 1 when either source has moved on from the pin, or a local copy was edited
 *
 * `--check` runs by hand in the release checklist; publish.yml has no cross-repo credential and never runs it.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = join(dirname(fileURLToPath(import.meta.url)), '..', 'eval', 'wording');
export const SOURCES = {
  list: { repo: 'andywilliams/block-site', path: 'ops/wording-banned.json', file: 'wording-banned.json' },
  port: { repo: 'andywilliams/dwlf-block-api', path: 'src/legibility/bannedWords.ts', file: 'bannedWords.mjs' },
};
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const gh = (...args) => execFileSync('gh', ['api', ...args], { maxBuffer: 1 << 24, stdio: ['ignore', 'pipe', 'pipe'] });
const headOf = (repo) => gh(`repos/${repo}/commits/main`, '--jq', '.sha').toString().trim();
const raw = (repo, path, commit) => gh(`repos/${repo}/contents/${path}?ref=${commit}`, '-H', 'Accept: application/vnd.github.raw');

// The port's source as of dwlf-block-api 92ce69b: one JSON import and `name: string` / `): string | null` annotations.
const JSON_IMPORT = "import list from './wording-banned.json';";
/** dwlf-block-api's bannedWords.ts as plain ESM. Throws on anything but the shape it was written for. */
export const toEsm = (ts, { repo, commit, path }) => {
  if (!ts.includes(JSON_IMPORT)) { throw new Error(`${path}: the JSON import changed; update toEsm before syncing`); }
  const js = ts
    .replace(JSON_IMPORT, "import { readFileSync } from 'node:fs';\n\nconst list = JSON.parse(readFileSync(new URL('./wording-banned.json', import.meta.url), 'utf8'));")
    .replace(/\((\w+): string\)/g, '($1)')
    .replace(/\): string(?: \| null)? \{/g, ') {');
  const leftover = js.split('\n').filter((l) => !/^\s*(\/\/|\*|\/\*\*)/.test(l)).join('\n')
    .match(/:\s*(?:string|number|boolean|RegExp|null)\b|\binterface\b|\btype\s+\w+\s*=|\bas\s+\w+|<[A-Z]\w*>/);
  if (leftover) { throw new Error(`${path}: TypeScript left after the transform (${leftover[0]}); update toEsm before syncing`); }
  return `// GENERATED by \`npm run wording:sync\` from ${repo}@${commit} ${path}. Do not edit: change the source and sync.\n${js}`;
};

const readPins = () => JSON.parse(readFileSync(join(HERE, 'SOURCES.json'), 'utf8'));

const check = () => {
  const pins = readPins();
  const problems = [];
  const local = readFileSync(join(HERE, SOURCES.list.file));
  if (sha256(local) !== pins.list.sha256) { problems.push(`eval/wording/${SOURCES.list.file} was edited: its sha256 is not the pinned ${pins.list.sha256}`); }
  const generated = readFileSync(join(HERE, SOURCES.port.file), 'utf8');
  if (!generated.startsWith(`// GENERATED by \`npm run wording:sync\` from ${SOURCES.port.repo}@${pins.port.commit} `)) {
    problems.push(`eval/wording/${SOURCES.port.file} does not name the pinned port commit ${pins.port.commit}`);
  }
  for (const [name, src] of Object.entries(SOURCES)) {
    const head = headOf(src.repo);
    const now = sha256(raw(src.repo, src.path, head));
    if (now !== pins[name].sha256) { problems.push(`${src.repo} ${src.path} moved on: main ${head.slice(0, 7)} has sha256 ${now.slice(0, 12)}…, pinned ${pins[name].sha256.slice(0, 12)}… (${pins[name].commit.slice(0, 7)})`); }
  }
  if (problems.length) { console.error(`wording:sync --check failed:\n- ${problems.join('\n- ')}\nRun npm run wording:sync and commit the result.`); return 1; }
  console.log(`wording list and port match their sources (list ${pins.list.sha256.slice(0, 12)}…, port ${pins.port.commit.slice(0, 7)})`);
  return 0;
};

const sync = async () => {
  const pins = {};
  const listCommit = headOf(SOURCES.list.repo);
  const list = raw(SOURCES.list.repo, SOURCES.list.path, listCommit);
  JSON.parse(list.toString('utf8'));
  writeFileSync(join(HERE, SOURCES.list.file), list);
  pins.list = { repo: SOURCES.list.repo, path: SOURCES.list.path, commit: listCommit, sha256: sha256(list) };

  const portCommit = headOf(SOURCES.port.repo);
  const ts = raw(SOURCES.port.repo, SOURCES.port.path, portCommit);
  const esm = toEsm(ts.toString('utf8'), { repo: SOURCES.port.repo, commit: portCommit, path: SOURCES.port.path });
  // Prove the generated module loads and flags before it replaces the vendored one.
  const dir = mkdtempSync(join(tmpdir(), 'dwlf-wording-'));
  writeFileSync(join(dir, SOURCES.list.file), list);
  writeFileSync(join(dir, SOURCES.port.file), esm);
  const { bannedWordIn } = await import(pathToFileURL(join(dir, SOURCES.port.file)).href);
  if (bannedWordIn('you should buy') === null || bannedWordIn('supply in profit') !== null) { throw new Error('the generated port does not behave like the list'); }
  writeFileSync(join(HERE, SOURCES.port.file), esm);
  pins.port = { repo: SOURCES.port.repo, path: SOURCES.port.path, commit: portCommit, sha256: sha256(ts) };

  // The Block API pins the same list; say so when it does not, so the two repos are synced together.
  let apiPin = '(unreadable)';
  try { apiPin = raw(SOURCES.port.repo, 'src/legibility/WORDING_SHA256', portCommit).toString().trim(); } catch { /* keep the note */ }
  pins._comment = 'Written by npm run wording:sync. list: block-site\'s export, vendored byte for byte. port: dwlf-block-api\'s bannedWordIn, as plain ESM. sha256 is of each source file as fetched.';
  writeFileSync(join(HERE, 'SOURCES.json'), `${JSON.stringify(pins, null, 1)}\n`);
  console.log(`list ${listCommit.slice(0, 7)} sha256 ${pins.list.sha256}; port ${portCommit.slice(0, 7)}; dwlf-block-api pins list ${apiPin}${apiPin === pins.list.sha256 ? ' (same)' : ' (DIFFERS: sync dwlf-block-api too)'}`);
  return 0;
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const run = process.argv.includes('--check') ? Promise.resolve().then(check) : sync();
  run.then((code) => process.exit(code), (error) => { console.error(`wording:sync: ${error.message}`); process.exit(2); });
}
